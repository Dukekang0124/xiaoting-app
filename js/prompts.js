export function cardThemeFor(score, isHighRisk) {
  const s = Number(score) || 0;
  if (isHighRisk) return 'ash';
  if (s >= 55) return 'warm';
  if (s >= 15) return 'blue';
  if (s <= -25) return 'ash';
  return 'purple';
}

