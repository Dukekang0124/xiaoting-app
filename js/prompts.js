/**
 * 把任意「原词数组 / 文本」归一化为标准展示短词（模块一交付物）。
 * 支持两种输入：① 关键词 / 原词数组；② 一段文本（按关键词扫描）。
 * 返回去重、保序的标准展示短词数组（最多 2 个，与节点规则一致）。
 */
export function mapTimelineToDisplay(labelsOrText, { limit = 2 } = {}) {
  const text = Array.isArray(labelsOrText) ? labelsOrText.join(' ') : String(labelsOrText || '');
  const found = [];
  for (const w of Object.keys(EMOTION_TRIGGERS)) {
    if (text.includes(w)) found.push(EMOTION_TRIGGERS[w]);
  }
  const seen = new Set();
  const out = [];
  for (const d of found) { if (!seen.has(d)) { seen.add(d); out.push(d); } }
  return out.slice(0, limit);
}

