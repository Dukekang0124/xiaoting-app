export function greetByHour(h = new Date().getHours()) {
  if (h >= 5 && h < 12) return COPY.greet.morning;
  if (h >= 12 && h < 18) return COPY.greet.afternoon;
  if (h >= 18 && h < 23) return COPY.greet.evening;
  return COPY.greet.lateNight;
}

